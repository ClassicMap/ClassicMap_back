-- 바로크 수동 작곡가 9명은 처음 입력할 때 tier 가 빠져 NULL 이었다(2025-12 백업부터).
-- 같은 가문의 C.P.E. 바흐·J.C. 바흐는 A 인데 J.S. 바흐가 비어 추천순에서 A 뒤로 밀렸다.
-- 고전주의가 S 3명(모차르트·베토벤·하이든), A 에 슈타미츠·클레멘티를 둔 기준에 맞춘다.
--   S: 바흐(4) · 헨델(6) · 비발디(7)
--   A: 몬테베르디(5) · 퍼셀(8) · D. 스카를라티(9) · 라모(10) · 텔레만(11) · 코렐리(12)
-- 편집 잠금 행이지만 이 9개 id 에 한해 사용자가 2026-09-17 명시적으로 허용했다.
-- 이미 tier 가 있으면 덮어쓰지 않는다. 다시 실행해도 결과가 같다.

UPDATE composers
SET tier = 'S'
WHERE id IN (4, 6, 7)
  AND tier IS NULL;

UPDATE composers
SET tier = 'A'
WHERE id IN (5, 8, 9, 10, 11, 12)
  AND tier IS NULL;
